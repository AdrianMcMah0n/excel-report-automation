"""Generate the demo inputs: 4 branches x 3 months of sales exports, each branch with its own messy layout.
Every branch, product and number is invented. Planted problems: re-exported duplicate rows, product-name
variants, an unknown product, a line whose total does not match qty x price, a missing date, a return
(negative quantity), blank rows, title rows above the header and a 'Total' row at the bottom.

    python samples/make_inputs.py
"""
import csv
import random
from datetime import date, timedelta
from pathlib import Path

from openpyxl import Workbook

HERE = Path(__file__).parent
IN = HERE / 'input'
PRODUCTS = [('Steel Bottle 1L', 'Drinkware', 549), ('Ceramic Mug', 'Drinkware', 299), ('Bamboo Cutting Board', 'Kitchen', 799),
            ('Cast Iron Pan 26cm', 'Kitchen', 1899), ('Cotton Apron', 'Textiles', 449), ('Linen Napkins (4)', 'Textiles', 699),
            ('Glass Storage Jar', 'Storage', 349), ('Spice Rack', 'Storage', 1199)]
VARIANTS = {'Steel Bottle 1L': 'steel bottle 1 l', 'Ceramic Mug': 'CERAMIC MUG', 'Cast Iron Pan 26cm': 'Cast-Iron Pan 26 cm'}
MONTHS = [(2026, 9), (2026, 10), (2026, 11)]
GROWTH = {'north': 1.00, 'south': 1.10, 'east': 0.95, 'west': 1.05}


def lines(rnd, branch, y, m):
    out, start = [], date(y, m, 1)
    for i in range(rnd.randint(55, 75)):
        name, _, price = rnd.choice(PRODUCTS)
        qty = max(1, int(rnd.gauss(3, 2) * GROWTH[branch] * (1 + 0.04 * (m - 9))))
        d = start + timedelta(days=rnd.randint(0, 27))
        if rnd.random() < 0.08 and name in VARIANTS:
            name = VARIANTS[name]
        out.append([f'{branch[0].upper()}{m:02d}-{i + 1:04d}', d, name, qty, price, qty * price])
    return out


def plant(rnd, rows, branch, m):
    rows += [rows[3][:], rows[10][:]]                                       # re-exported duplicates
    if branch == 'east' and m == 10:
        rows.append(['E10-0901', date(2026, 10, 14), 'Copper Kettle', 2, 2499, 4998])    # not in the product list
    if branch == 'north' and m == 11:
        r = rows[5]; r[5] = r[3] * r[4] + 500                                # total does not match qty x price
    if branch == 'south' and m == 9:
        rows.append(['S09-0902', None, 'Ceramic Mug', 1, 299, 299])          # missing date
    if branch == 'west' and m == 11:
        rows.append(['W11-0903', date(2026, 11, 20), 'Spice Rack', -1, 1199, -1199])     # a return
    rnd.shuffle(rows)
    return rows


def write_north(rows, path):     # CSV, dd/mm/yyyy, amounts with thousands separators
    with path.open('w', newline='', encoding='utf-8') as f:
        w = csv.writer(f)
        w.writerow(['Order No', 'Order Date', 'Product', 'Qty', 'Unit Price', 'Total'])
        for inv, d, p, q, pr, t in rows:
            w.writerow([inv, d.strftime('%d/%m/%Y') if d else '', p, q, f'{pr:,.2f}', f'{t:,.2f}'])


def write_south(rows, path):     # XLSX, real dates, lower-case headers, a blank row in the middle
    wb = Workbook(); ws = wb.active
    ws.append(['invoice', 'date', 'item', 'quantity', 'price', 'amount (INR)'])
    for i, r in enumerate(rows):
        if i == 20:
            ws.append([])
        ws.append(r)
    wb.save(path)


def write_east(rows, path):      # CSV, ISO dates, 'Rs.' amounts
    with path.open('w', newline='', encoding='utf-8') as f:
        w = csv.writer(f)
        w.writerow(['Txn ID', 'Txn Date', 'SKU Name', 'Units', 'Rate', 'Sales'])
        for inv, d, p, q, pr, t in rows:
            w.writerow([inv, d.isoformat() if d else '', p, q, f'Rs. {pr:,}', f'Rs. {t:,}'])


def write_west(rows, path):      # XLSX, title rows above the header, a Total row at the bottom
    wb = Workbook(); ws = wb.active
    ws.append(['West branch sales export']); ws.append(['Generated by POS']); ws.append([])
    ws.append(['Invoice No', 'Invoice Date', 'Product Name', 'Qty Sold', 'Selling Price', 'Line Total'])
    for r in rows:
        ws.append(r)
    ws.append(['Total', None, None, None, None, sum(r[5] for r in rows)])
    wb.save(path)


if __name__ == '__main__':
    rnd = random.Random(2026)
    IN.mkdir(parents=True, exist_ok=True)
    writers = {'north': (write_north, 'csv'), 'south': (write_south, 'xlsx'), 'east': (write_east, 'csv'), 'west': (write_west, 'xlsx')}
    for y, m in MONTHS:
        for branch, (write, ext) in writers.items():
            rows = plant(rnd, lines(rnd, branch, y, m), branch, m)
            path = IN / f'{branch}_{y}-{m:02d}.{ext}'
            write(rows, path)
            print('wrote', path.name, len(rows), 'rows')
    with (IN.parent / 'products.csv').open('w', newline='', encoding='utf-8') as f:
        w = csv.writer(f)
        w.writerow(['product', 'category', 'list_price'])
        w.writerows(PRODUCTS)
