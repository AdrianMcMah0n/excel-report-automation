from datetime import date, datetime

from report.load_clean import ProductMatcher, find_header, to_date, to_number

PRODUCTS = [{'product': 'Steel Bottle 1L', 'category': 'Drinkware'}, {'product': 'Cast Iron Pan 26cm', 'category': 'Kitchen'}]


def test_header_found_below_title_rows():
    rows = [['West branch sales export'], ['Generated by POS'], [],
            ['Invoice No', 'Invoice Date', 'Product Name', 'Qty Sold', 'Selling Price', 'Line Total']]
    i, cols = find_header(rows)
    assert i == 3 and cols == {'invoice': 0, 'date': 1, 'product': 2, 'qty': 3, 'price': 4, 'total': 5}


def test_amounts_in_any_format():
    assert to_number('1,234.50') == 1234.5
    assert to_number('Rs. 2,397') == 2397
    assert to_number('₹ 1,199') == 1199
    assert to_number(42) == 42.0
    assert to_number('n/a') is None


def test_dates_day_first():
    assert to_date('03/11/2026') == date(2026, 11, 3)          # 3 November, not 11 March
    assert to_date('2026-10-23') == date(2026, 10, 23)
    assert to_date(datetime(2026, 9, 1, 0, 0)) == date(2026, 9, 1)
    assert to_date('') is None and to_date('31/02/2026') is None


def test_product_variants_and_unknowns():
    m = ProductMatcher(PRODUCTS)
    assert m.match('Steel Bottle 1L') == (PRODUCTS[0], '')
    hit, note = m.match('steel bottle 1 l')
    assert hit == PRODUCTS[0] and 'read as' in note
    assert m.match('Cast-Iron Pan 26 cm')[0] == PRODUCTS[1]
    assert m.match('Copper Kettle') == (None, '')
